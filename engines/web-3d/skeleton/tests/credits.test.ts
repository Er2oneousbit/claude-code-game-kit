//           marks off (#284) against every case in data/golden/credits.json, and the text it shows for a file as
//           tools/credits.py writes it.
// Usage   : python tools/dev.py test
// Notes   : A case type this file does not know fails. Expected values of the golden part come only from the JSON.
// Authored: Written with Claude (Opus 5.5, claude-opus-5-5)
// Updated : 2026-11-13 with Claude (Opus 5.5, claude-opus-5-5): the credits_text cases; the screen's text has no
//           "#" or "- " marks (#284)
// ---------------------------------------------------------------------------
import { describe, expect, it } from "vitest";
import { creditsMarkdownText, creditsText, stripHtmlComments } from "../src/shell/credits";
import { loadGolden, type GoldenCase } from "./helpers/golden";

const golden = loadGolden("credits.json");

const RUNNERS: Record<string, (c: GoldenCase) => void> = {
  strip_comments: (c) => {
    c.points.forEach(([name, text, want]: [string, string, string]) => expect(stripHtmlComments(text), name).toBe(want));
  },
  credits_text: (c) => {
    c.points.forEach(([name, text, want]: [string, string, string]) => expect(creditsMarkdownText(text), name).toBe(want));
  },
};

describe("credits golden vectors (data/golden/credits.json)", () => {
  it("has cases", () => {
    expect(golden.cases.length).toBeGreaterThan(0);
  });

  for (const c of golden.cases) {
    it(`${c.type}: ${c.name}`, () => {
      const run = Object.prototype.hasOwnProperty.call(RUNNERS, c.type) ? RUNNERS[c.type] : undefined;
      if (!run) throw new Error(`unknown case type "${c.type}": add a runner for it (tools/golden_vectors.py is the spec)`);
      run(c);
    });
  }
});

describe("creditsText", () => {
  it("shows a CREDITS.md from tools/credits.py without its comment or markdown marks", () => {
    const md = "# Credits\r\n\r\n<!-- Generated by tools/credits.py from docs/ASSET_LOG.md: edit the asset log, " +
      "not this file. -->\r\n\r\n## Music\r\n\r\n<!--\r\nnotes\r\n-->\r\n- Song by **Zoë** (CC0)\r\n";
    expect(creditsText(md)).toBe("Credits\n\nMusic\n\nSong by Zoë (CC0)");
  });

  it("is null (the placeholder) for no file or a file that holds only a comment", () => {
    expect(creditsText(undefined)).toBeNull();
    expect(creditsText("<!-- nothing yet -->\n")).toBeNull();
  });
});

