-- ---------------------------------------------------------------------------
-- test_credits_text.lua
-- Purpose : The credits screen's text (src/shell/screens/credits.lua): HTML comments out of CREDITS.md (#279) and the
--           markdown marks off (#284) against every case in data/golden/credits.json, and the lines it scrolls for a
--           file as tools/credits.py writes it.
-- Usage   : python tools/dev.py test     (or --filter credits)
-- Notes   : The expected values of the golden part come from the file at test time (tools/golden_vectors.py writes it).
-- Authored: Written with Claude (Opus 5.5, claude-opus-5-5)
-- Updated : 2026-11-13 with Claude (Opus 5.5, claude-opus-5-5): the credits_text cases (#284)
-- ---------------------------------------------------------------------------
local A = require("tests.assert")
local Golden = require("tests.helpers.golden")
local Credits = require("src.shell.screens.credits")

local FILE = "credits.json"
local data = Golden.load(FILE)

local handlers = {}

function handlers.strip_comments(case, _, where)
  for i, p in ipairs(case.points) do
    local got = Credits.strip_html_comments(p[2])
    if got ~= p[3] then
      error(where .. " point " .. i .. " (" .. p[1] .. "): expected " .. string.format("%q", p[3]) .. ", got " ..
            string.format("%q", got), 0)
    end
  end
  return #case.points
end

function handlers.credits_text(case, _, where)
  for i, p in ipairs(case.points) do
    local got = Credits.text(p[2])
    if got ~= p[3] then
      error(where .. " point " .. i .. " (" .. p[1] .. "): expected " .. string.format("%q", p[3]) .. ", got " ..
            string.format("%q", got), 0)
    end
  end
  return #case.points
end

local T = Golden.suite(data, handlers, FILE)

function T.test_a_credits_md_from_credits_py_shows_no_comment()
  local md = "# Credits\r\n\r\n<!-- Generated by tools/credits.py from docs/ASSET_LOG.md: edit the asset log, " ..
             "not this file. -->\r\n\r\n## Music\r\n\r\n<!--\r\nnotes\r\n-->\r\n- Song by **Zo\195\171** (CC0)\r\n"
  A.same(Credits.lines_from(md), { "Credits", "", "Music", "", "Song by Zo\195\171 (CC0)" })
end

function T.test_a_file_with_only_a_comment_shows_the_placeholder()
  A.eq(Credits.lines_from("<!-- nothing yet -->\n"), nil)
end

return T

