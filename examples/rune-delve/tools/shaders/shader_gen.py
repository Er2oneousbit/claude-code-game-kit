class ToolError(Exception):
    pass


# ---- recipes -----------------------------------------------------------------------------------------------------------
def gl_type(value):
    if isinstance(value, list):
        return f"vec{len(value)}"
    return "float"


def load():
    """[{name, params: [(name, type, default)], main, aux, body}]"""
    data = json.loads(RECIPES.read_text(encoding="utf-8"))
    out = []
    for name, r in data["recipes"].items():
        path = KSL_DIR / f"{name}.ksl"
        if not path.is_file():
            raise ToolError(f"recipe {name} has no {path.name}")
        params = [(k, gl_type(v), v) for k, v in r["params"].items()]
        params += [("canvas", "vec2", list(map(float, data["canvas"]))), ("texel", "vec2", [1 / 32, 1 / 32])]
        ins = r["inputs"]
        out.append({"name": name, "group": r["group"], "summary": r["summary"], "params": params,
                    "main": ins[0], "aux": ins[1] if len(ins) > 1 else None,
                    "body": path.read_text(encoding="utf-8").strip("\n")})
    return out


def glsl_value(t, v):
    if t == "float":
        return _num(v)
    return f"{t}({', '.join(_num(x) for x in v)})"


def _num(x):
    s = repr(float(x))
    return s if ("." in s or "e" in s) else s + ".0"


# ---- translation -------------------------------------------------------------------------------------------------------
def _args(text, start):
    """(end index, [top-level arguments]) of the call whose '(' is at text[start]."""
    depth, args, cur, i = 0, [], "", start
    while i < len(text):
        ch = text[i]
        if ch == "(":
            depth += 1
            if depth == 1:
                i += 1
                continue
        elif ch == ")":
            depth -= 1
            if depth == 0:
                args.append(cur)
                return i, args
        elif ch == "," and depth == 1:
            args.append(cur)
            cur = ""
            i += 1
            continue
        cur += ch
        i += 1
    raise ToolError(f"unbalanced parentheses in: {text.strip()}")


def rewrite_calls(text, name, fn):
    """Replace every call name(...) (outermost first, arguments rewritten too) with fn(list of argument strings)."""
    out, i = "", 0
    pat = re.compile(r"\b" + re.escape(name) + r"\(")
    while True:
        m = pat.search(text, i)
        if not m:
            return out + text[i:]
        end, args = _args(text, m.end() - 1)
        args = [rewrite_calls(a, name, fn) for a in args]
        out += text[i:m.start()] + fn([a.strip() for a in args])
        i = end + 1


def to_hlsl(body):
    for n in (2, 3, 4):
        body = rewrite_calls(body, f"vec{n}", lambda a, n=n: f"((float{n})({a[0]}))" if len(a) == 1
                             else f"float{n}({', '.join(a)})")
        body = re.sub(rf"\bvec{n}\b", f"float{n}", body)
    body = re.sub(r"\bfract\(", "frac(", body)
    body = re.sub(r"\bmix\(", "lerp(", body)
    return body


# Bevy's material bind group, built so this file holds no double-brace name, which the scaffolder reads as a placeholder
BIND = "constants::MATERIAL_BIND_GROUP"   # Bevy 0.20 WESL: the material bind group index
WGSL_TYPES = {"float": "f32", "vec2": "vec2<f32>", "vec3": "vec3<f32>", "vec4": "vec4<f32>"}


def to_wgsl(body):
    body = re.sub(r"^(\s*)(float|vec2|vec3|vec4) (\w+) = ",
                  lambda m: f"{m.group(1)}var {m.group(3)}: {WGSL_TYPES[m.group(2)]} = ", body, flags=re.M)
    body = re.sub(r"\bvec([234])\(", r"vec\1<f32>(", body)
    body = re.sub(r"\bu_(\w+)", r"params.\1", body)
    return body


def indent(body, n=4):
    return "\n".join((" " * n + line) if line.strip() else line for line in body.split("\n"))


# ---- engine wrappers ---------------------------------------------------------------------------------------------------
def godot(r):
    uniforms = "\n".join(f"uniform {t} u_{k} = {glsl_value(t, v)};" for k, t, v in r["params"])
    aux = "uniform sampler2D kit_aux : filter_nearest, repeat_disable;\n" if r["aux"] else ""
    post = r["group"] == "post"
    main_decl = "uniform sampler2D kit_screen : hint_screen_texture, filter_nearest;\n" if post else ""
    body = r["body"].replace("SAMPLE_MAIN(", "texture(main_tex, ").replace("SAMPLE_AUX(", "texture(kit_aux, ")
    call = "kit_effect(SCREEN_UV, kit_screen)" if post else "kit_effect(UV, TEXTURE)"
    return (f"// {HEADER_NOTE.format(name=r['name'])}\n// {r['summary']}\n"
            f"shader_type canvas_item;\n\n{main_decl}{aux}{uniforms}\n\n"
            f"vec4 kit_effect(vec2 uv, sampler2D main_tex) {{\n{indent(body)}\n}}\n\n"
            f"void fragment() {{\n    COLOR = {call};\n}}\n")


def glsl_es1(r, flip, prelude, main_name, aux_name, out_line, coord):
    """GLSL ES 1.00 fragment shader: Phaser filters, PIXI filters (MZ), Three.js ShaderMaterial, the check page."""
    uniforms = "\n".join(f"uniform {t} u_{k};" for k, t, v in r["params"])
    aux = f"uniform sampler2D {aux_name};\n" if r["aux"] else ""
    flipdef = "#define KIT_FLIP(p) vec2((p).x, 1.0 - (p).y)" if flip else "#define KIT_FLIP(p) (p)"
    helpers = f"vec4 SAMPLE_MAIN(vec2 p) {{ return texture2D({main_name}, KIT_FLIP(p)); }}\n"
    if r["aux"]:
        helpers += f"vec4 SAMPLE_AUX(vec2 p) {{ return texture2D({aux_name}, KIT_FLIP(p)); }}\n"
    return (f"{prelude}precision highp float;\n// {HEADER_NOTE.format(name=r['name'])}\n{flipdef}\n"
            f"uniform sampler2D {main_name};\n{aux}{uniforms}\nvarying vec2 {coord};\n{helpers}\n"
            f"vec4 kit_effect(vec2 uv) {{\n{indent(r['body'])}\n}}\n\n"
            f"void main() {{\n    {out_line}\n}}\n")


def js_module(recipes, flip, kind):
    """One JS/TS module: every recipe's GLSL and default parameters, for the web overlays and MZ."""
    if kind == "phaser":
        frags = {r["name"]: glsl_es1(r, flip, "#pragma phaserTemplate(shaderName)\n", "uMainSampler", "uAuxSampler",
                                      "gl_FragColor = kit_effect(KIT_FLIP(outTexCoord));", "outTexCoord")
                 for r in recipes}
    elif kind == "pixi":
        frags = {r["name"]: pixi(r) for r in recipes}
    else:
        frags = {r["name"]: glsl_es1(r, flip, "", "uMainSampler", "uAuxSampler",
                                      "gl_FragColor = kit_effect(KIT_FLIP(vTextureCoord));", "vTextureCoord")
                 for r in recipes}
    meta = {r["name"]: {"group": r["group"], "main": r["main"], "aux": r["aux"],
                        "params": {k: v for k, _, v in r["params"]}} for r in recipes}
    head = (f"// {HEADER_NOTE.format(name='*')}\n// The kit's shader recipes: GLSL ES 1.00 fragment shaders and their "
            "default parameters (u_<name> uniforms).\n")
    return (head + f"export const KIT_SHADER_FLIP_Y = {str(flip).lower()};\n"
            f"export const KIT_SHADERS = {json.dumps(meta, indent=1)};\n"
            f"export const KIT_FRAGMENTS = {json.dumps(frags, indent=1)};\n")


def pixi(r):
    """GLSL for a PIXI 5 filter (RPG Maker MZ): the input is uSampler, and vTextureCoord covers the filter frame,
    which PIXI pads to its texture size: image space is vTextureCoord * inputSize.xy / outputFrame.zw."""
    uniforms = "\n".join(f"uniform {t} u_{k};" for k, t, v in r["params"])
    aux = "uniform sampler2D uAuxSampler;\n" if r["aux"] else ""
    helpers = ("vec4 SAMPLE_MAIN(vec2 p) { return texture2D(uSampler, p * outputFrame.zw * inputSize.zw); }\n"
               + ("vec4 SAMPLE_AUX(vec2 p) { return texture2D(uAuxSampler, p); }\n" if r["aux"] else ""))
    return (f"precision highp float;\n// {HEADER_NOTE.format(name=r['name'])}\n"
            f"uniform sampler2D uSampler;\nuniform vec4 inputSize;\nuniform vec4 outputFrame;\n{aux}{uniforms}\n"
            f"varying vec2 vTextureCoord;\n{helpers}\n"
            f"vec4 kit_effect(vec2 uv) {{\n{indent(r['body'])}\n}}\n\n"
            "void main() {\n    gl_FragColor = kit_effect(vTextureCoord * inputSize.xy / outputFrame.zw);\n}\n")


MZ_RUNTIME = """
(() => {
  "use strict";
  const uniformsOf = (name, params) => {
    const all = Object.assign({}, KIT_SHADERS[name].params, params || {});
    const out = {};
    for (const [k, v] of Object.entries(all)) out["u_" + k] = Array.isArray(v) ? new Float32Array(v) : v;
    return out;
  };
  /**
   * A PIXI filter running one kit recipe. KitShaders.filter("flash", { amount: 1 }) on a sprite:
   *   sprite.filters = [KitShaders.filter("flash")]; later filter.uniforms.u_amount = 0;
   * A second input (dissolve's noise, palette_swap's palette, ...) is a PIXI texture: KitShaders.filter(name, {}, tex)
   */
  const filter = (name, params, auxTexture) => {
    if (!KIT_FRAGMENTS[name]) throw new Error("KitShaders: no recipe " + name);
    const uniforms = uniformsOf(name, params);
    if (auxTexture) uniforms.uAuxSampler = auxTexture;
    return new PIXI.Filter(null, KIT_FRAGMENTS[name], uniforms);
  };
  window.KitShaders = { filter, recipes: KIT_SHADERS, fragments: KIT_FRAGMENTS };
})();
"""


def mz_plugin(recipes):
    """RPG Maker MZ plugin: every recipe's PIXI filter GLSL and default parameters, and KitShaders.filter()."""
    meta = {r["name"]: {"group": r["group"], "main": r["main"], "aux": r["aux"],
                        "params": {k: v for k, _, v in r["params"]}} for r in recipes}
    frags = {r["name"]: pixi(r) for r in recipes}
    return ("//=============================================================================\n"
            "// KitShaders.js\n"
            f"// {HEADER_NOTE.format(name='*')}\n"
            "//=============================================================================\n"
            "/*:\n * @target MZ\n * @plugindesc The kit's shader recipes as PIXI filters (KitShaders.filter).\n"
            " * @help Generated: edit tools/shaders/ksl and run python tools/shaders/shader_gen.py.\n"
            " * Usage in a script or another plugin: sprite.filters = [KitShaders.filter(\"flash\", { amount: 1 })];\n"
            " * Checked against the recipes' golden images by: python tools/dev.py smoke --shaders\n */\n"
            f"const KIT_SHADERS = {json.dumps(meta, indent=1)};\n"
            f"const KIT_FRAGMENTS = {json.dumps(frags, indent=1)};\n" + MZ_RUNTIME)


def love(r):
    uniforms = "\n".join(f"uniform {t} u_{k};" for k, t, v in r["params"])
    aux = "uniform Image kit_aux;\n" if r["aux"] else ""
    body = r["body"].replace("SAMPLE_MAIN(", "Texel(main_tex, ").replace("SAMPLE_AUX(", "Texel(kit_aux, ")
    return (f"// {HEADER_NOTE.format(name=r['name'])}\n// {r['summary']}\n{aux}{uniforms}\n\n"
            f"vec4 kit_effect(vec2 uv, Image main_tex) {{\n{indent(body)}\n}}\n\n"
            "vec4 effect(vec4 color, Image tex, vec2 tc, vec2 sc) {\n    return kit_effect(tc, tex) * color;   // love.graphics.setColor tints it, as for any LOVE sprite\n}\n")


def love_params(recipes):
    def lua(v):
        if isinstance(v, list):
            return "{" + ", ".join(_num(x) for x in v) + "}"
        return _num(v)
    lines = [f"-- {HEADER_NOTE.format(name='*')}", "-- Default parameters of the kit's shader recipes (send() them as u_<name>).",
             "return {"]
    for r in recipes:
        ps = ", ".join(f"{k} = {lua(v)}" for k, _, v in r["params"])
        aux = f'"{r["aux"]}"' if r["aux"] else "nil"
        lines.append(f'  {r["name"]} = {{group = "{r["group"]}", main = "{r["main"]}", aux = {aux}, params = {{{ps}}}}},')
    return "\n".join(lines + ["}", ""])


def unity(r):
    def prop(k, t, v):
        if t == "float":
            return f'        u_{k} ("{k}", Float) = {_num(v)}'
        vals = list(v) + [0.0] * (4 - len(v))
        return f'        u_{k} ("{k}", Vector) = ({", ".join(_num(x) for x in vals)})'
    props = "\n".join(prop(k, t, v) for k, t, v in r["params"])
    aux_prop = '        _AuxTex ("Aux", 2D) = "black" {}\n' if r["aux"] else ""
    decls = "\n".join(f"            {to_hlsl(t)} u_{k};" for k, t, v in r["params"])
    aux_decl = "            sampler2D _AuxTex;\n" if r["aux"] else ""
    body = to_hlsl(r["body"]).replace("SAMPLE_MAIN(", "tex2Dlod(_MainTex, KitLod(").replace(
        "SAMPLE_AUX(", "tex2Dlod(_AuxTex, KitLod(")
    body = _close_lod(body)
    return f"""// {HEADER_NOTE.format(name=r['name'])}
// {r['summary']}
// kit-inputs: {r['main']} {r['aux'] or '-'}
Shader "Kit/{r['name']}"
{{
    Properties
    {{
        _MainTex ("Main", 2D) = "white" {{}}
{aux_prop}{props}
        [Enum(UnityEngine.Rendering.BlendMode)] _SrcBlend ("Src blend", Float) = 5
        [Enum(UnityEngine.Rendering.BlendMode)] _DstBlend ("Dst blend", Float) = 10
    }}
    SubShader
    {{
        Tags {{ "Queue"="Transparent" "RenderType"="Transparent" "IgnoreProjector"="True" }}
        Cull Off ZWrite Off ZTest Always
        Blend [_SrcBlend] [_DstBlend]
        Pass
        {{
            CGPROGRAM
            #pragma vertex vert
            #pragma fragment frag
            #pragma target 3.0
            #include "UnityCG.cginc"
            sampler2D _MainTex;
{aux_decl}{decls}
            struct appdata {{ float4 vertex : POSITION; float2 uv : TEXCOORD0; }};
            struct v2f {{ float4 pos : SV_POSITION; float2 uv : TEXCOORD0; }};
            v2f vert(appdata v) {{ v2f o; o.pos = UnityObjectToClipPos(v.vertex); o.uv = v.uv; return o; }}
            // Unity textures run bottom-up: image space (origin top-left) is flipped in and out
            float4 KitLod(float2 p) {{ return float4(p.x, 1.0 - p.y, 0.0, 0.0); }}
            float4 kit_effect(float2 uv)
            {{
{indent(body, 16)}
            }}
            float4 frag(v2f i) : SV_Target {{ return kit_effect(float2(i.uv.x, 1.0 - i.uv.y)); }}
            ENDCG
        }}
    }}
}}
"""


def _close_lod(body):
    """tex2Dlod(t, KitLod(x) -> tex2Dlod(t, KitLod(x)): the replacement opened one parenthesis more."""
    return rewrite_calls(body, "KitLod", lambda a: f"KitLod({a[0]}))") if "KitLod(" in body else body


def unreal_body(r):
    body = to_hlsl(r["body"])
    body = rewrite_calls(body, "SAMPLE_MAIN", lambda a: f"Texture2DSampleLevel(MainTex, MainTexSampler, {a[0]}, 0)")
    body = rewrite_calls(body, "SAMPLE_AUX", lambda a: f"Texture2DSampleLevel(AuxTex, AuxTexSampler, {a[0]}, 0)")
    return body


def unreal_module(recipes):
    meta = {r["name"]: {"group": r["group"], "main": r["main"], "aux": r["aux"], "code": unreal_body(r),
                        "params": {k: v for k, _, v in r["params"]}} for r in recipes}
    return (f"# {HEADER_NOTE.format(name='*')}\n# The kit's shader recipes as Unreal material Custom node HLSL: inputs uv "
            "(image space), MainTex, AuxTex and one input per parameter (u_<name>).\n"
            f"RECIPES = {pprint.pformat(meta, indent=1, width=118, sort_dicts=False)}\n")   # Python literals (None)


def bevy(r):
    """Bevy 0.20 WESL fragment shader for a Material2d (naga_oil and its #import are gone in 0.20)."""
    fields = "\n".join(f"    {k}: {WGSL_TYPES[t]}," for k, t, v in r["params"])
    aux = (f"@group({BIND}) @binding(3) var aux_tex: texture_2d<f32>;\n"
           f"@group({BIND}) @binding(4) var aux_samp: sampler;\n"
           f"fn SAMPLE_AUX(p: vec2<f32>) -> vec4<f32> {{ return textureSampleLevel(aux_tex, aux_samp, p, 0.0); }}\n"
           if r["aux"] else "")
    return (f"import bevy_sprite_render::mesh2d::vertex_output::VertexOutput;\n\n"
            f"// {HEADER_NOTE.format(name=r['name'])}\n// {r['summary']}\n\n"
            f"struct KitParams {{\n{fields}\n}}\n\n"
            f"@group({BIND}) @binding(0) var<uniform> params: KitParams;\n"
            f"@group({BIND}) @binding(1) var main_tex: texture_2d<f32>;\n"
            f"@group({BIND}) @binding(2) var main_samp: sampler;\n"
            f"{aux}fn SAMPLE_MAIN(p: vec2<f32>) -> vec4<f32> {{ return textureSampleLevel(main_tex, main_samp, p, 0.0); }}\n\n"
            f"fn kit_effect(uv: vec2<f32>) -> vec4<f32> {{\n{indent(to_wgsl(r['body']))}\n}}\n\n"
            f"@fragment\nfn fragment(in: VertexOutput) -> @location(0) vec4<f32> {{\n    return kit_effect(in.uv);\n}}\n")


RUST_TYPES = {"float": "f32", "vec2": "Vec2", "vec3": "Vec3", "vec4": "Vec4"}


def _camel(name):
    return "".join(part.capitalize() for part in name.split("_"))


def _rust_value(t, v):
    if t == "float":
        return _num(v)
    return f"{RUST_TYPES[t]}::new({', '.join(_num(x) for x in v)})"


def bevy_rust(recipes):
    """src/kit_shaders.rs: per recipe a params struct (encase lays it out as the WESL struct), a Material2d, and the
    plugin that registers them all; spawn_recipe() serves the shader check."""
    out = [f"// {HEADER_NOTE.format(name='*')}",
           "// The kit's shader recipes as Bevy 2D materials: add KitShadersPlugin, then",
           "//   MeshMaterial2d(materials.add(FlashMaterial { params: FlashParams { amount: 1.0, ..default() }, main: tex }))",
           "// on an entity with Mesh2d(meshes.add(Rectangle::new(w, h))). Shaders: assets/shaders/kit/<name>.wesl.",
           "#![allow(clippy::all)]",
           "use bevy::prelude::*;",
           "use bevy::render::render_resource::{AsBindGroup, ShaderType};",
           "use bevy::shader::ShaderRef;",
           "use bevy::sprite_render::{AlphaMode2d, Material2d, Material2dPlugin};",
           "",
           "/// (name, main input, aux input) of every recipe, in recipes.json order.",
           "pub const KIT_RECIPES: &[(&str, &str, Option<&str>)] = &["]
    for r in recipes:
        aux = f'Some("{r["aux"]}")' if r["aux"] else "None"
        out.append(f'    ("{r["name"]}", "{r["main"]}", {aux}),')
    out += ["];", ""]
    for r in recipes:
        c = _camel(r["name"])
        blend = "Blend" if r["group"] in ("sprite", "lighting") else "Opaque"
        out += [f"/// {r['summary']}",
                "#[derive(Clone, Copy, Debug, ShaderType)]",
                f"pub struct {c}Params {{"]
        out += [f"    pub {k}: {RUST_TYPES[t]}," for k, t, v in r["params"]]
        out += ["}", "",
                f"impl Default for {c}Params {{",
                "    fn default() -> Self {",
                "        Self {"]
        out += [f"            {k}: {_rust_value(t, v)}," for k, t, v in r["params"]]
        out += ["        }", "    }", "}", "",
                "#[derive(Asset, TypePath, AsBindGroup, Clone, Debug)]",
                f"pub struct {c}Material {{",
                "    #[uniform(0)]",
                f"    pub params: {c}Params,",
                "    #[texture(1)]",
                "    #[sampler(2)]",
                "    pub main: Handle<Image>,"]
        if r["aux"]:
            out += ["    #[texture(3)]", "    #[sampler(4)]", "    pub aux: Handle<Image>,"]
        out += ["}", "",
                f"impl Material2d for {c}Material {{",
                "    fn fragment_shader() -> ShaderRef {",
                f'        "shaders/kit/{r["name"]}.wesl".into()',
                "    }",
                "",
                "    fn alpha_mode(&self) -> AlphaMode2d {",
                f"        AlphaMode2d::{blend}",
                "    }",
                "}", ""]
    out += ["/// Registers every recipe's material.",
            "pub struct KitShadersPlugin;",
            "",
            "impl Plugin for KitShadersPlugin {",
            "    fn build(&self, app: &mut App) {"]
    out += [f"        app.add_plugins(Material2dPlugin::<{_camel(r['name'])}Material>::default());" for r in recipes]
    out += ["    }", "}", "",
            "/// Spawn `bundle` with recipe `name`'s material at its default parameters. False for an unknown name.",
            "pub fn spawn_recipe(world: &mut World, name: &str, main: Handle<Image>, aux: Option<Handle<Image>>,",
            "                    bundle: impl Bundle) -> bool {",
            "    match name {"]
    for r in recipes:
        c = _camel(r["name"])
        aux = " aux: aux.unwrap_or_default()," if r["aux"] else ""
        out += [f'        "{r["name"]}" => {{',
                f"            let m = world.resource_mut::<Assets<{c}Material>>()",
                f"                .add({c}Material {{ params: {c}Params::default(), main,{aux} }});",
                "            world.spawn((bundle, MeshMaterial2d(m)));",
                "        }"]
    out += ["        _ => return false,", "    }", "    true", "}", ""]
    return "\n".join(out)

def sdl3(r):
    """HLSL for SDL3's GPU API (compiled to DXIL / SPIR-V): textures in space2, uniforms in space3 (SDL's layout)."""
    fields = "\n".join(f"    {to_hlsl(t)} u_{k};" for k, t, v in r["params"])
    aux = ("Texture2D<float4> AuxTex : register(t1, space2);\nSamplerState AuxSampler : register(s1, space2);\n"
           "float4 SAMPLE_AUX(float2 p) { return AuxTex.SampleLevel(AuxSampler, p, 0); }\n" if r["aux"] else "")
    return f"""// {HEADER_NOTE.format(name=r['name'])}
// {r['summary']}
Texture2D<float4> MainTex : register(t0, space2);
SamplerState MainSampler : register(s0, space2);
{aux}cbuffer KitParams : register(b0, space3)
{{
{fields}
}};
float4 SAMPLE_MAIN(float2 p) {{ return MainTex.SampleLevel(MainSampler, p, 0); }}

float4 kit_effect(float2 uv)
{{
{indent(to_hlsl(r['body']))}
}}

float4 main(float2 uv : TEXCOORD0) : SV_Target0
{{
    return kit_effect(uv);
}}
"""


