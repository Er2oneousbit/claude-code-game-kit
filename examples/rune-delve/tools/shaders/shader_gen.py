#!/usr/bin/env python3
# ---------------------------------------------------------------------------
# shader_gen.py
# Purpose : Turns the kit's shader recipes (tools/shaders/ksl/<name>.ksl, one body each, plus their parameters in
#           recipes.json) into each engine's shader files: Godot .gdshader, GLSL for Phaser, Three.js, PIXI (RPG Maker
#           MZ) and LOVE, HLSL for Unity, Unreal and the C++ overlay (SDL3 GPU), WGSL for Bevy. One source, nine ports.
# Usage   : python tools/shaders/shader_gen.py                  # this game's engine (from .game-kit.json): write
#           python tools/shaders/shader_gen.py --check          # are this game's generated files current? (exit 1)
#           python tools/shaders/shader_gen.py --engine godot --out <folder>   # any engine, any folder
#           python tools/shaders/shader_gen.py --list-engines
# Exit    : 0 ok, 1 generated files are stale (--check), 2 usage
# Notes   : KSL is a small, strict subset of GLSL so the translation stays textual and checkable:
#             - one statement per line; declarations are `float|vec2|vec3|vec4 name = expr;`
#             - SAMPLE_MAIN(uv) and SAMPLE_AUX(uv) read the recipe's two inputs, nearest-neighbour, in image space
#               (origin top-left); each engine's wrapper flips y where its textures run bottom-up
#             - parameters are u_<name> (floats, vec2, vec3), plus u_canvas (the check canvas, 64 x 64) and u_texel
#               (one input texel, 1 / 32); vecN(x) with one argument fills every component
#             - always braces after if/else, no ternary, no loops, no matrices (write dot products)
#           Generated files carry a "generated by shader_gen.py" header: edit the .ksl and regenerate, never the output.
# Authored: Written with Claude (Opus 5.5, claude-opus-5-5)
# ---------------------------------------------------------------------------
#
# Pseudocode
#   recipes.json + ksl/<name>.ksl -> per recipe: params (name, type, default), main/aux inputs, body
#   per engine: translate the body (GLSL as is; HLSL types and builtins; WGSL declarations, types, params.<name>)
#   -> wrap it in the engine's file format -> write, or with --check compare with what is on disk
