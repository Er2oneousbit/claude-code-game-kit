def files_for(engine, recipes):
    if engine == "godot":
        return {f"{r['name']}.gdshader": godot(r) for r in recipes}
    if engine == "web":
        return {"kitShaders.ts": js_module(recipes, True, "phaser")}
    if engine == "web-3d":
        return {"kitShaders.ts": js_module(recipes, True, "three")}   # Three's uv and flipY textures run bottom-up
    if engine == "rpgmaker-mz":
        return {"KitShaders.js": mz_plugin(recipes)}   # PIXI textures run top-down: no flip
    if engine == "love2d":
        out = {f"{r['name']}.glsl": love(r) for r in recipes}
        out["params.lua"] = love_params(recipes)
        return out
    if engine == "unity":
        return {f"{r['name']}.shader": unity(r) for r in recipes}
    if engine == "unreal":
        return {"kit_recipes.py": unreal_module(recipes)}
    if engine == "bevy":
        out = {f"assets/shaders/kit/{r['name']}.wesl": bevy(r) for r in recipes}
        out["src/kit_shaders.rs"] = bevy_rust(recipes)
        return out
    if engine == "cpp-sdl2":
        return {f"{r['name']}.frag.hlsl": sdl3(r) for r in recipes}
    raise ToolError(f"no shader port for engine {engine!r}: {', '.join(ENGINE_DIRS)}")


def game_engine():
    try:
        return json.loads((ROOT / ".game-kit.json").read_text(encoding="utf-8"))["engine"]
    except (OSError, ValueError, KeyError):
        raise ToolError("no .game-kit.json naming the engine here: pass --engine")


def write_or_check(engine, out_dir, check):
    recipes = load()
    stale = []
    for rel, text in files_for(engine, recipes).items():
        path = out_dir / rel
        data = text.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
    return stale


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser(description="Generate each engine's shader files from the kit's recipes (KSL).",
                                 epilog="Exit codes: 0 ok, 1 generated files stale (--check), 2 usage.")
    ap.add_argument("--engine", help=f"one of {', '.join(ENGINE_DIRS)} (default: this game's engine)")
    ap.add_argument("--out", help="folder to write into (default: the engine's folder in this game)")
    ap.add_argument("--check", action="store_true", help="only report whether the files are current")
    ap.add_argument("--list-engines", action="store_true", help="print the engines and their folders")
    args = ap.parse_args(argv)
    try:
        if args.list_engines:
            for e, d in ENGINE_DIRS.items():
                print(f"{e:12s} {d}")
            return 0
        engine = args.engine or game_engine()
        if engine not in ENGINE_DIRS:
            raise ToolError(f"no shader port for engine {engine!r}")
        out_dir = Path(args.out) if args.out else ROOT / ENGINE_DIRS[engine]
        stale = write_or_check(engine, out_dir, args.check)
    except ToolError as exc:
        print(f"[error] {exc}", file=sys.stderr)
        return 2
    if args.check:
        for p in stale:
            print(f"[FAIL] stale: {p} (run shader_gen.py without --check)")
        if not stale:
            print(f"[ OK ] {engine} shader files are current")
        return 1 if stale else 0
    print(f"[ OK ] {engine} shader files written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
