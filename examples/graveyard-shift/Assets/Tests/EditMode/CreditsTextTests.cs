using System.Collections.Generic;
using NUnit.Framework;
using graveyard_shift.Core;
using G = graveyard_shift.Tests.GoldenVectors;

namespace graveyard_shift.Tests
{
    public class CreditsTextTests
    {
        private const string FILE = "credits.json";

        public static IEnumerable<TestCaseData> Cases()
        {
            return G.CaseData(FILE, "Credits");
        }

        [TestCaseSource(nameof(Cases))]
        public void Credits(int index)
        {
            Dictionary<string, object> c = G.Case(FILE, index);
            string type = G.Str(c, "type");
            switch (type)
            {
                case "strip_comments":
                    int n = 0;
                    foreach (object p in G.List(c, "points"))
                    {
                        var pt = (List<object>)p;
                        Assert.AreEqual((string)pt[2], CreditsText.StripHtmlComments((string)pt[1]), (string)pt[0]);
                        n++;
                    }
                    Assert.Greater(n, 0, "no points");
                    break;
                case "credits_text":
                    int m = 0;
                    foreach (object p in G.List(c, "points"))
                    {
                        var pt = (List<object>)p;
                        Assert.AreEqual((string)pt[2], CreditsText.Plain((string)pt[1]), (string)pt[0]);
                        m++;
                    }
                    Assert.Greater(m, 0, "no points");
                    break;
                default:
                    Assert.Fail($"unknown case type '{type}' in {FILE}: add a runner for it here");
                    break;
            }
        }

        [Test]
        public void Credits_AFileFromCreditsPyShowsNoComment()
        {
            string md = "# Credits\r\n\r\n<!-- Generated by tools/credits.py from docs/ASSET_LOG.md: edit the asset log, "
                      + "not this file. -->\r\n\r\n## Music\r\n\r\n<!--\r\nnotes\r\n-->\r\n- Song by **Zoë** (CC0)\r\n- Ana\r\n";
            CollectionAssert.AreEqual(new[] { "Credits", "Music", "Song by Zoë (CC0)\nAna" }, CreditsText.Blocks(md));
        }

        [Test]
        public void Credits_NoFileOrOnlyACommentShowsThePlaceholder()
        {
            Assert.IsNull(CreditsText.Blocks(null));
            Assert.IsNull(CreditsText.Blocks("<!-- nothing yet -->\n"));
        }
    }
}
